"""Exports SQLite applications and job pipeline to a clean applications.md tracker."""

from datetime import datetime, timezone
from pathlib import Path
from src.storage.database import Database
from src.config import APPLICATIONS_MD_PATH


class ApplicationTracker:
    def __init__(self, db: Database):
        self.db = db

    def export_markdown(self, output_path: Path = APPLICATIONS_MD_PATH) -> Path:
        jobs = self.db.get_all_jobs()

        lines = [
            "# 📋 Job Application Tracker",
            f"\n*Auto-generated by apply-assist on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}*\n",
            "## Summary",
            f"- **Total Discovered Jobs:** {len(jobs)}",
            f"- **Applied / In Review:** {len([j for j in jobs if j.status in ('APPLIED', 'INTERVIEW')])}",
            f"- **Matched (Score >= 3):** {len([j for j in jobs if (j.fit_score or 0) >= 3])}",
            "\n---\n",
            "## Application Pipeline",
            "\n| Company | Role | Location | ATS | Fit Score | Risk Level | Status | Job URL |",
            "| :--- | :--- | :--- | :--- | :---: | :---: | :---: | :--- |"
        ]

        if not jobs:
            lines.append("| *None* | *None* | *None* | *None* | - | - | - | - |")
        else:
            for j in jobs:
                score_display = f"⭐ {j.fit_score}/5" if j.fit_score else "-"
                risk_display = f"`{j.risk_level}`" if j.risk_level else "-"
                status_display = f"**{j.status}**" if j.status in ("APPLIED", "MATCHED") else j.status
                title_clean = j.title.replace("|", "-")
                company_clean = j.company.replace("|", "-")
                lines.append(
                    f"| {company_clean} | {title_clean} | {j.location} | {j.ats_type} | {score_display} | {risk_display} | {status_display} | [Link]({j.url}) |"
                )

        content = "\n".join(lines) + "\n"
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)

        return output_path
